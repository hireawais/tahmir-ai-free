    /**
     * Return a safe SQL ORDER BY clause from allowlisted columns.
     *
     * @param string $orderby Requested order key.
     * @param string $order Requested direction.
     * @param array  $allowed Map of request key => SQL column/expression.
     * @param string $default_key Default request key.
     * @param string $default_order Default direction.
     * @return string Safe "column ASC|DESC" fragment.
     */
    public static function sanitize_sql_order($orderby, $order, $allowed, $default_key, $default_order = 'DESC')
    {
        $allowed = is_array($allowed) ? $allowed : [];
        $key = sanitize_key((string) $orderby);
        $default_key = sanitize_key((string) $default_key);
        $column = $allowed[$key] ?? ($allowed[$default_key] ?? reset($allowed));

        if (!is_string($column) || $column === '') {
            $column = 'id';
        }

        $direction = strtoupper((string) $order);
        if (!in_array($direction, ['ASC', 'DESC'], true)) {
            $direction = strtoupper((string) $default_order) === 'ASC' ? 'ASC' : 'DESC';
        }

        $fragment = sanitize_sql_orderby($column . ' ' . $direction);
        if (!$fragment) {
            $fallback = sanitize_sql_orderby(($allowed[$default_key] ?? 'id') . ' ' . $direction);
            return $fallback ?: 'id DESC';
        }

        return $fragment;
    }

    /**
     * Clamp a request integer to a safe range.
     *
     * @param mixed $value Input value.
     * @param int   $min Minimum value.
     * @param int   $max Maximum value.
     * @return int
     */
    public static function clamp_int($value, $min, $max)
    {
        return max((int) $min, min((int) $max, (int) $value));
    }

    /**
     * Detect unsafe archive paths before extraction.
     *
     * @param string $path Archive entry path.
     * @return bool
     */
    public static function is_unsafe_archive_path($path)
    {
        $path = str_replace('\\', '/', (string) $path);
        if ($path === '' || strpos($path, "\0") !== false) {
            return true;
        }

        // Colons include drive-relative names and NTFS alternate data streams.
        if ($path[0] === '/' || preg_match('/[:\x00-\x1f\x7f]/', $path)) {
            return true;
        }

        foreach (explode('/', rtrim($path, '/')) as $part) {
            if ($part === '.') {
                continue;
            }
            if ($part === '..' || preg_match('/[. ]$/', $part)
                || preg_match('/^(?:con|prn|aux|nul|com[1-9]|lpt[1-9])(?:\.|$)/i', $part)) {
                return true;
            }
        }
        return false;
    }

    /**
     * Check whether a path resolves inside an allowed root.
     *
     * @param string $path Path to check.
     * @param string $root Allowed root.
     * @return bool
     */
    public static function path_is_inside($path, $root)
    {
        $normalized = str_replace('\\', '/', (string) $path);
        if (strpos($normalized, "\0") !== false) {
            return false;
        }
        $root_real = realpath($root);
        if ($root_real === false) {
            return false;
        }

        $root_norm = trailingslashit(wp_normalize_path($root_real));

        if (file_exists($path)) {
            $path_real = realpath($path);
            if ($path_real === false) {
                return false;
            }

            $path_norm = wp_normalize_path($path_real);
            return $path_norm === untrailingslashit($root_norm) || strpos(trailingslashit($path_norm), $root_norm) === 0;
        }

        // Existing paths are checked using realpath; unresolved suffixes must
        // not smuggle traversal past the nearest existing parent check.
        if (in_array('..', explode('/', $normalized), true)) {
            return false;
        }
        $parent = dirname($path);
        $suffix = basename($path);
        while (!file_exists($parent) && dirname($parent) !== $parent) {
            $suffix = basename($parent) . '/' . $suffix;
            $parent = dirname($parent);
        }

        $parent_real = realpath($parent);
        if ($parent_real === false) {
            return false;
        }

        $path_norm = wp_normalize_path(trailingslashit($parent_real) . $suffix);
        return $path_norm === untrailingslashit($root_norm) || strpos(trailingslashit($path_norm), $root_norm) === 0;
    }

    /**
     * Validate uploaded file size, extension, and MIME.
     *
     * @param array $file $_FILES entry.
     * @param array $allowed_mimes Allowed MIME types.
     * @param int   $max_bytes Maximum size.
     * @param array $allowed_exts Optional allowed extensions.
     * @return array|WP_Error
     */
    public static function validate_uploaded_file($file, $allowed_mimes, $max_bytes, $allowed_exts = [])
    {
        if (empty($file) || !is_array($file) || empty($file['tmp_name'])) {
            return new WP_Error('ugentic_missing_upload', __('No file was uploaded.', 'tahmir-ai-to-wp-converter'));
        }

        if (!empty($file['error']) && (int) $file['error'] !== UPLOAD_ERR_OK) {
            return new WP_Error('ugentic_upload_error', __('File upload failed.', 'tahmir-ai-to-wp-converter'));
        }

        $size = (int) ($file['size'] ?? 0);
        if ($size <= 0 || ($max_bytes > 0 && $size > $max_bytes)) {
            return new WP_Error('ugentic_upload_size', __('Uploaded file size is not allowed.', 'tahmir-ai-to-wp-converter'));
        }

        $name = sanitize_file_name($file['name'] ?? '');
        $ext = strtolower(pathinfo($name, PATHINFO_EXTENSION));
        $allowed_exts = array_map('strtolower', (array) $allowed_exts);
        if (!empty($allowed_exts) && !in_array($ext, $allowed_exts, true)) {
            return new WP_Error('ugentic_upload_extension', __('Uploaded file extension is not allowed.', 'tahmir-ai-to-wp-converter'));
        }

        $mime = '';
        if (function_exists('finfo_open')) {
            $finfo = finfo_open(FILEINFO_MIME_TYPE);
            if ($finfo) {
                $mime = (string) finfo_file($finfo, $file['tmp_name']);
                finfo_close($finfo);
            }
        }

        $allowed_mimes = array_map('strtolower', (array) $allowed_mimes);
        if ($mime === '' || !in_array(strtolower($mime), $allowed_mimes, true)) {
            return new WP_Error('ugentic_upload_mime', __('Uploaded file type is not allowed.', 'tahmir-ai-to-wp-converter'));
        }

        return [
            'name' => $name,
            'extension' => $ext,
            'mime' => $mime,
            'size' => $size,
        ];
    }

    /**
     * Validate a server-side fetch target before WordPress makes the request.
     *
     * @param string $url URL to validate.
     * @param string $context Short caller context for filters/logging.
     * @return true|WP_Error
     */
    public static function validate_remote_url($url, $context = 'remote_fetch')
    {
        $url = esc_url_raw((string) $url);

        if (empty($url)) {
            return new WP_Error('ugentic_empty_url', __('Empty URL.', 'tahmir-ai-to-wp-converter'));
        }

        $parts = wp_parse_url($url);
        if (empty($parts['scheme']) || empty($parts['host'])) {
            return new WP_Error('ugentic_invalid_url', __('Invalid URL.', 'tahmir-ai-to-wp-converter'));
        }

        $scheme = strtolower($parts['scheme']);
        if (!in_array($scheme, ['http', 'https'], true)) {
            return new WP_Error('ugentic_invalid_scheme', __('Only HTTP and HTTPS URLs are allowed.', 'tahmir-ai-to-wp-converter'));
        }

        $host = strtolower(trim($parts['host'], "[] \t\n\r\0\x0B"));
        if ($host === '') {
            return new WP_Error('ugentic_invalid_host', __('Invalid URL host.', 'tahmir-ai-to-wp-converter'));
        }

        if (apply_filters('ugentic_allow_private_remote_fetch', false, $url, $context)) {
            return true;
        }

        $ips = self::resolve_host_ips($host);
        if (empty($ips)) {
            return new WP_Error('ugentic_unresolvable_host', __('Could not resolve URL host.', 'tahmir-ai-to-wp-converter'));
        }

        foreach ($ips as $ip) {
            if (!self::is_public_ip($ip)) {
                return new WP_Error(
                    'ugentic_private_remote_fetch',
                    __('Private, local, and reserved network addresses cannot be fetched.', 'tahmir-ai-to-wp-converter')
                );
            }
        }

        return true;
    }

    /**
     * Safe wrapper around wp_remote_get for user-controlled external URLs.
     *
     * @param string $url URL to fetch.
     * @param array  $args wp_remote_get arguments.
     * @param string $context Short caller context.
     * @return array|WP_Error
     */
    public static function remote_get($url, $args = [], $context = 'remote_fetch')
    {
        $validation = self::validate_remote_url($url, $context);
        if (is_wp_error($validation)) {
            return $validation;
        }

        $allow_private = (bool) apply_filters('ugentic_allow_private_remote_fetch', false, $url, $context);
        $args = wp_parse_args($args, [
            'sslverify' => true,
            'reject_unsafe_urls' => !$allow_private,
        ]);
        $args['reject_unsafe_urls'] = !$allow_private;
        $args['sslverify'] = (bool) apply_filters('ugentic_remote_fetch_sslverify', true, $url, $context);

        return wp_remote_get($url, $args);
    }

