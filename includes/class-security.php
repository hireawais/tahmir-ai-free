    /**
     * Remove active content from imported HTML. Imported pages originate from
     * arbitrary ZIPs/URLs and otherwise execute with the WordPress site origin.
     */
    public static function strip_imported_active_content($html)
    {
        $html = (string) $html;
        // Use the HTML tokenizer for attributes: browsers accept slash separators,
        // mixed case and entities that a whitespace-only regex can miss.
        if (class_exists('WP_HTML_Tag_Processor')) {
            $processor = new WP_HTML_Tag_Processor($html);
            while ($processor->next_tag()) {
                foreach ((array) $processor->get_attribute_names_with_prefix('on') as $attribute) {
                    $processor->remove_attribute($attribute);
                }
                $processor->remove_attribute('srcdoc');
                foreach (['href', 'xlink:href', 'src', 'action', 'formaction', 'data', 'poster', 'background'] as $attribute) {
                    $value = $processor->get_attribute($attribute);
                    if (!is_string($value)) {
                        continue;
                    }
                    $decoded = preg_replace('/[\x00-\x20\x7f]+/', '', html_entity_decode(rawurldecode($value), ENT_QUOTES | ENT_HTML5, 'UTF-8'));
                    $safe_image = $attribute === 'src' && preg_match('/^data:image\/(?:png|jpeg|gif|webp|avif);base64,/i', $decoded);
                    if (preg_match('/^(?:javascript|vbscript):/i', $decoded)
                        || (stripos($decoded, 'data:') === 0 && !$safe_image)) {
                        $processor->set_attribute($attribute, '#');
                    }
                }
            }
            $html = $processor->get_updated_html();
        }
        $html = preg_replace('/<script\b[^>]*>[\s\S]*?<\/script\s*>/i', '', $html);
        $html = preg_replace('/<script\b[^>]*>[\s\S]*$/i', '', $html);
        $html = preg_replace('/<link\b(?=[^>]*(?:rel\s*=\s*(["\'])?modulepreload\1|as\s*=\s*(["\'])?script\2))[^>]*>/i', '', $html);
        $html = preg_replace('/\s+on[a-z0-9_-]+\s*=\s*(?:"[^"]*"|\'[^\']*\'|[^\s>]+)/i', '', $html);
        $html = preg_replace('/\s+srcdoc\s*=\s*(?:"[^"]*"|\'[^\']*\'|[^\s>]+)/i', '', $html);
        $html = preg_replace_callback('/\s(href|xlink:href|src|action|formaction|data|poster|background)\s*=\s*(?:"([^"]*)"|\'([^\']*)\'|([^\s>]+))/is', function ($match) {
            $value = $match[2] !== '' ? $match[2] : (($match[3] ?? '') !== '' ? $match[3] : ($match[4] ?? ''));
            $decoded = preg_replace('/[\x00-\x20\x7f]+/', '', html_entity_decode(rawurldecode($value), ENT_QUOTES | ENT_HTML5, 'UTF-8'));
            $is_data = stripos($decoded, 'data:') === 0;
            $safe_data_image = strtolower($match[1]) === 'src'
                && preg_match('/^data:image\/(?:png|jpeg|gif|webp|avif);base64,/i', $decoded);
            if (preg_match('/^(?:javascript|vbscript):/i', $decoded) || ($is_data && !$safe_data_image)) {
                return ' ' . $match[1] . '="#"';
            }
            return $match[0];
        }, $html);
        // These elements can execute or navigate independently of script tags.
        $html = preg_replace('/<(?:iframe|object|embed|base|meta\b(?=[^>]*http-equiv)|set|animate|animateMotion|animateTransform)\b[^>]*>/i', '', $html);
        return $html;
    }

    /**
     * Resolve a script copied into a Tahmir-owned import namespace.
     *
     * Callers still verify the recorded byte count and SHA-256. This helper
     * only proves that the relative path belongs to a narrowly named import
     * directory and that its real path cannot escape that directory.
     *
     * @param string $relative Relative path below the WordPress uploads root.
     * @param string $base_dir WordPress uploads directory.
     * @return array|false
     */
    public static function resolve_verified_imported_script_path($relative, $base_dir)
    {
        $relative = ltrim(wp_normalize_path((string) $relative), '/');
        $base_dir = (string) $base_dir;
        if ($relative === '' || $base_dir === '' || strpos($relative, '..') !== false) {
            return false;
        }

        $root_relative = '';
        if (preg_match('#^(ugentic-assets/ugentic-import-[a-f0-9]{8,64})/.+\.(?:js|mjs|cjs)$#i', $relative, $namespace)) {
            $root_relative = $namespace[1];
        } elseif (preg_match('#^(ugentic-clones/ugentic-clone-[a-f0-9]{8,64})/.+\.(?:js|mjs|cjs)$#i', $relative, $namespace)) {
            $root_relative = $namespace[1];
        } else {
            return false;
        }

        $base_real = realpath($base_dir);
        $root_real = realpath(trailingslashit($base_dir) . $root_relative);
        $file_real = realpath(trailingslashit($base_dir) . str_replace('/', DIRECTORY_SEPARATOR, $relative));
        if (!$base_real || !$root_real || !$file_real || !is_file($file_real)) {
            return false;
        }

        $base_prefix = strtolower(trailingslashit(wp_normalize_path($base_real)));
        $root_prefix = strtolower(trailingslashit(wp_normalize_path($root_real)));
        $normalized_file = strtolower(wp_normalize_path($file_real));
        if (strpos($root_prefix, $base_prefix) !== 0 || strpos($normalized_file, $root_prefix) !== 0) {
            return false;
        }

        return [
            'relative' => $relative,
            'file' => $file_real,
            'root' => $root_real,
        ];
    }

    public static function imported_scripts_are_allowed()
    {
        $settings = (array) get_option('ugentic_settings', []);
        return !empty($settings['allow_imported_scripts']);
    }

    /**
     * Whether this authenticated builder request explicitly enables imported code.
     *
     * This is intentionally request-scoped and never available to public edit
     * tokens. Imported scripts execute with the WordPress site origin, so only a
     * user who may submit unfiltered HTML can opt into the mode.
     */
    public static function builder_full_code_mode_is_enabled()
    {
        if (
            !is_user_logged_in()
            || !current_user_can('edit_pages')
            || !current_user_can('unfiltered_html')
        ) {
            return false;
        }

        $builder_mode = isset($_GET['tahmir_builder'])
            ? sanitize_key(wp_unslash((string) $_GET['tahmir_builder']))
            : '';
        $safe_mode = isset($_GET['tahmir_safe_mode'])
            ? sanitize_key(wp_unslash((string) $_GET['tahmir_safe_mode']))
            : '';

        return in_array($builder_mode, ['1', 'builder', 'ai'], true)
            && in_array($safe_mode, ['1', 'on', 'true'], true);
    }
